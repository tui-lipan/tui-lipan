#!/usr/bin/env bash
#
# Regenerates src/bindings.rs from the libghostty-vt headers with bindgen-cli
# (`cargo install bindgen-cli --locked`). Run it after bumping VERSION in build.rs:
#
#   ghostty-vt-sys/scripts/generate-bindings.sh [include-dir]
#
# include-dir defaults to the headers of the source tree the build script unpacked, so build
# the crate once first. The output targets 64-bit platforms; the layout assertions bindgen
# writes fail to compile anywhere the C layout differs.

set -euo pipefail

crate_dir="$(cd "$(dirname "$0")/.." && pwd)"
workspace_dir="$(cd "$crate_dir/.." && pwd)"
include_dir="${1:-$workspace_dir/target/ghostty-vt/src/libghostty-vt-1.0.1/include}"

if [[ ! -f "$include_dir/ghostty/vt.h" ]]; then
    echo "no ghostty/vt.h under $include_dir; build ghostty-vt-sys once or pass the include dir" >&2
    exit 1
fi

out="$crate_dir/src/bindings.rs"

# C23 gives every enum the `: int` type the Zig side uses (GHOSTTY_ENUM_TYPED). In older C modes
# an enum with no negative value would come out unsigned.
bindgen "$crate_dir/scripts/wrapper.h" \
    --output "$out" \
    --rust-target 1.85 \
    --rust-edition 2024 \
    --use-core \
    --allowlist-item '(ghostty|Ghostty|GHOSTTY)_?.*' \
    --blocklist-item 'ghostty_wasm_.*' \
    --default-enum-style consts \
    --no-prepend-enum-name \
    --no-doc-comments \
    --wrap-unsafe-ops \
    --merge-extern-blocks \
    --sort-semantically \
    --raw-line '// Generated by scripts/generate-bindings.sh from libghostty-vt 1.0.1. Do not edit.' \
    -- \
    -std=c23 \
    -DGHOSTTY_STATIC \
    -I "$include_dir"

echo "wrote $out"

# bindgen cannot evaluate the GHOSTTY_MODE_* macros, which call the static inline
# ghostty_mode_new(). lib.rs defines that function; these constants come straight from modes.h.
modes_out="$crate_dir/src/modes.rs"
{
    echo '// Generated by scripts/generate-bindings.sh from libghostty-vt 1.0.1. Do not edit.'
    echo
    echo 'use crate::{GhosttyMode, ghostty_mode_new};'
    echo
    sed -nE 's|^#define (GHOSTTY_MODE_[A-Z0-9_]+) +\(ghostty_mode_new\(([0-9]+), (true\|false)\)\) */\*\*< (.*) \*/$|/// \4\npub const \1: GhosttyMode = ghostty_mode_new(\2, \3);|p' \
        "$include_dir/ghostty/vt/modes.h"
} >"$modes_out"
count="$(grep -c '^pub const' "$modes_out")"
expected="$(grep -cE '^#define GHOSTTY_MODE_' "$include_dir/ghostty/vt/modes.h")"
if [[ "$count" != "$expected" ]]; then
    echo "modes.rs has $count modes but modes.h defines $expected" >&2
    exit 1
fi
echo "wrote $modes_out ($count modes)"
