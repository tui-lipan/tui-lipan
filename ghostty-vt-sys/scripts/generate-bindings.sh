#!/usr/bin/env bash
#
# Regenerates src/bindings.rs from the libghostty-vt headers with bindgen-cli
# (`cargo install bindgen-cli --locked`). Run it after bumping LIBGHOSTTY_VT_VERSION in
# src/versions.rs:
#
#   ghostty-vt-sys/scripts/generate-bindings.sh [include-dir]
#
# Bindings come from the unpatched release headers: src/lib.rs declares the functions tui-lipan's
# patch adds by hand. include-dir defaults to the headers of the pinned release tarball that
# scripts/package-ghostty-src.sh downloads into target/ghostty-vt/dl, so run that first. The
# output targets 64-bit platforms; the layout assertions bindgen writes fail to compile anywhere
# the C layout differs.

set -euo pipefail

crate_dir="$(cd "$(dirname "$0")/.." && pwd)"
workspace_dir="$(cd "$crate_dir/.." && pwd)"
version="$(sed -nE 's/^pub const LIBGHOSTTY_VT_VERSION: &str = "([^"]+)";$/\1/p' "$crate_dir/src/versions.rs")"
if (($#)); then
    include_dir="$1"
else
    tarball="$workspace_dir/target/ghostty-vt/dl/libghostty-vt-$version.tar.gz"
    if [[ ! -f "$tarball" ]]; then
        echo "no $tarball; run scripts/package-ghostty-src.sh or pass the include dir" >&2
        exit 1
    fi
    unpacked="$workspace_dir/target/ghostty-vt/headers"
    rm -rf "$unpacked"
    mkdir -p "$unpacked"
    tar -xzf "$tarball" -C "$unpacked" "libghostty-vt-$version/include"
    include_dir="$unpacked/libghostty-vt-$version/include"
fi

if [[ ! -f "$include_dir/ghostty/vt.h" ]]; then
    echo "no ghostty/vt.h under $include_dir" >&2
    exit 1
fi

out="$crate_dir/src/bindings.rs"

# C23 gives every enum the `: int` type the Zig side uses (GHOSTTY_ENUM_TYPED). In older C modes
# an enum with no negative value would come out unsigned.
bindgen "$crate_dir/scripts/wrapper.h" \
    --output "$out" \
    --rust-target 1.85 \
    --rust-edition 2024 \
    --use-core \
    --allowlist-item '(ghostty|Ghostty|GHOSTTY)_?.*' \
    --blocklist-item 'ghostty_wasm_.*' \
    --default-enum-style consts \
    --no-prepend-enum-name \
    --no-doc-comments \
    --wrap-unsafe-ops \
    --merge-extern-blocks \
    --sort-semantically \
    --raw-line "// Generated by scripts/generate-bindings.sh from libghostty-vt $version. Do not edit." \
    -- \
    -std=c23 \
    -DGHOSTTY_STATIC \
    -I "$include_dir"

echo "wrote $out"

# bindgen cannot evaluate the GHOSTTY_MODE_* macros, which call the static inline
# ghostty_mode_new(). lib.rs defines that function; these constants come straight from modes.h.
modes_out="$crate_dir/src/modes.rs"
{
    echo "// Generated by scripts/generate-bindings.sh from libghostty-vt $version. Do not edit."
    echo
    echo 'use crate::{GhosttyMode, ghostty_mode_new};'
    echo
    sed -nE 's|^#define (GHOSTTY_MODE_[A-Z0-9_]+) +\(ghostty_mode_new\(([0-9]+), (true\|false)\)\) */\*\*< (.*) \*/$|/// \4\npub const \1: GhosttyMode = ghostty_mode_new(\2, \3);|p' \
        "$include_dir/ghostty/vt/modes.h"
} >"$modes_out"
count="$(grep -c '^pub const' "$modes_out")"
expected="$(grep -cE '^#define GHOSTTY_MODE_' "$include_dir/ghostty/vt/modes.h")"
if [[ "$count" != "$expected" ]]; then
    echo "modes.rs has $count modes but modes.h defines $expected" >&2
    exit 1
fi
echo "wrote $modes_out ($count modes)"
