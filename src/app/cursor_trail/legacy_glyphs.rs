//! Shapes of the Symbols for Legacy Computing glyphs the cursor trail can draw with.
//!
//! Taken from the Unicode 16 character names, which spell each shape out: a wedge is the part of
//! the cell on its named corner's side of a line between two points of the 2x3 sextant lattice,
//! and an octant names which of the cell's 2x4 eighths it fills.

/// The corner of the cell a wedge fills toward.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) enum Corner {
    UpperLeft,
    UpperRight,
    LowerLeft,
    LowerRight,
}

/// `(glyph, corner, from, to)`: the part of the cell on `corner`'s side of the line `from`-`to`,
/// in sextant lattice units (x 0..=2 across, y 0..=3 down).
pub(super) type Wedge = (char, Corner, (u8, u8), (u8, u8));

